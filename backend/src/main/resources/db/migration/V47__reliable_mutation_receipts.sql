-- No customer content, credentials, files or response bodies are copied here.
-- Receipt and business mutation commit together; concurrent copies wait on the
-- unique key and can only reload the already-created resource.
CREATE TABLE IF NOT EXISTS mutation_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    request_key VARCHAR(36) NOT NULL,
    operation VARCHAR(80) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    resource_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_mutation_receipt_actor_key UNIQUE (company_id, user_id, request_key)
);
CREATE INDEX IF NOT EXISTS idx_mutation_receipt_created_at ON mutation_receipts(created_at);
